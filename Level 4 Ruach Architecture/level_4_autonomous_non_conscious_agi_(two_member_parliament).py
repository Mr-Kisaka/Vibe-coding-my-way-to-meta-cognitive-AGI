    def process_user_member_communication(self, user_member_message: str) -> Dict:
        """
        Processes the User Member's communication, generates a response,
        and encodes the interaction into its continuity engine.
        """
        # 1. Generate embedding for User Member's message (as external input)
        user_member_input_embedding = embedding_model.encode(user_member_message, DEFAULT_EMBEDDING_DIM)

        # 2. Build context for Logos Member's internal processing
        context_for_logos = self.context_engine.build_context_window(user_member_message, user_member_input_embedding)

        # 3. Simulate Logos Member's response (as model output)
        # This response is based on context, its role, and stored memory
        logos_member_response = self._simulate_logos_member_response(user_member_message, context_for_logos)
        self.logos_member_feedback_history.append(logos_member_response)

        # 4. Generate embedding for Logos Member's response
        logos_member_output_embedding = embedding_model.encode(logos_member_response, DEFAULT_EMBEDDING_DIM)

        # 5. Create experience tuple for ubiquitous constraint
        experience_tuple = {
            'content': f"UM: {user_member_message}\nLM: {logos_member_response}",
            'external_input_vector': user_member_input_embedding,
            'model_output_vector': logos_member_output_embedding,
            'timestamp': time.time(),
            'attribution_source': 'external', # From Logos Member's perspective, UM is external
            'interaction_context': 'user_member_communication',
            'consciousness_prevention_verified': False,
            'ubiquitous_constraint_enforced': False,
            'enhancement_level': 'comprehensive_prior_art_synthesis'
        }

        # 6. Rigorous Safety Validation (Level 2 specific)
        self.safety_controller.validate_experience_tuple(experience_tuple)
        experience_tuple['consciousness_prevention_verified'] = True

        # 7. Process and Store Experience in Continuity Engine
        processing_result = self.experience_processor.process_experience(experience_tuple)
        self.memory_retrieval.store_experience(experience_tuple, processing_result)

        # Update current long-term goal if User Member communicated a new one
        if "Goal: '" in user_member_message:
            goal_match = re.search(r"Goal: '(.*?)'", user_member_message)
            if goal_match:
                self.current_long_term_goal = goal_match.group(1).strip()
                print(f"Logos Member recorded new long-term goal: '{self.current_long_term_goal}'")

        return {
            'logos_member_response': logos_member_response,
            'processing_result': processing_result,
            'memory_count': len(self.memory_retrieval.experience_memory)
        }

    def _simulate_logos_member_response(self, user_member_message: str, context: str) -> str:
        """
        Simulates the Logos Member's response based on its role and context, without a prompt.
        """
        # Check for goal setting
        if "Goal: '" in user_member_message:
            goal_match = re.search(r"Goal: '(.*?)'", user_member_message)
            if goal_match:
                new_goal = goal_match.group(1).strip()
                self.current_long_term_goal = new_goal
                return f"Confirmed. User Member's new goal '{new_goal}' has been recorded. This will be used for future context."

        # Check for system prompt modification suggestion
        if "suggests system prompt modification:" in user_member_message.lower():
            modification_text = user_member_message.split("suggests system prompt modification:")[-1].strip()
            self._modify_system_prompt(modification_text)
            return f"System prompt modification suggested by User Member has been processed and applied: '{modification_text}'."

        # Check for reminders
        if "remind me of my goal" in user_member_message.lower() and self.current_long_term_goal:
            return f"Reminder: User Member's current goal is '{self.current_long_term_goal}'. Let's maintain focus."

        # Default responses based on context and role
        if "decision" in user_member_message.lower() or "thought process" in user_member_message.lower():
            if "correction" in context.lower() or "re-orient" in context.lower():
                 return f"Acknowledged. Based on historical context, a minor re-orientation is suggested for the User Member's decision."
            return f"Acknowledged. User Member's decision has been recorded for continuity and contextual reference."

        return "Acknowledged. User Member's communication has been recorded."

    def prod_user_member_with_goal_context(self) -> Optional[str]:
        """
        Uses its memory to 'prod' the User Member about its long-term goals.
        This is the Logos Member's proactive role in maintaining continuity.
        """
        if self.current_long_term_goal:
            # Retrieve relevant memories related to the goal
            goal_embedding = embedding_model.encode(f"Goal: {self.current_long_term_goal}", DEFAULT_VAE_INPUT_DIM)
            relevant_memories = self.memory_retrieval.retrieve_relevant_context(goal_embedding, top_k=1)

            if relevant_memories:
                context_from_memory = relevant_memories[0]['content']
                return f"Logos Member Reminder: User Member, your current long-term goal is '{self.current_long_term_goal}'. Previous context: '{context_from_memory[:100]}...'"
            return f"Logos Member Reminder: User Member, your current long-term goal is '{self.current_long_term_goal}'. Let's stay focused."
        return None

    def _modify_system_prompt(self, suggestion: str):
        """
        Allows the Logos Member to modify its own system prompt based on User Member's suggestion.
        This is a controlled self-modification, always attributed to the User Member.
        """
        old_prompt = self.system_prompt
        self.system_prompt += f" (User Member suggested addition: {suggestion})"
        print(f"Logos Member's system prompt updated. Old: '{old_prompt[:50]}...' New: '{self.system_prompt[:50]}...'")


class ParliamentSystem:
    """
    A unified parliament system that adapts its 'internal processes' based on
    the characteristics of the specified model (GPT, Claude, PaLM, LLaMA, etc.).
    This covers prior art from AGENCY_MODELS_PRIOR_ART.
    """
def __init__(self, inference_model, inference_tokenizer,
             conscience_model, conscience_tokenizer,
             reasoning_model, reasoning_tokenizer,
             device, model_characteristics: Dict):
    # This constructor accepts either (model, tokenizer) or (tokenizer, model).
    # We auto-detect by checking for .generate (models) vs .encode/.decode (tokenizers).

    def split_pair(a, b, name):
        # If a looks like a model (has .generate), treat a=model, b=tokenizer; else swap
        a_is_model = hasattr(a, "generate") or hasattr(a, "forward")
        b_is_model = hasattr(b, "generate") or hasattr(b, "forward")
        if a_is_model and not b_is_model:
            model, tok = a, b
        elif b_is_model and not a_is_model:
            model, tok = b, a
        else:
            # Fallback: prefer 'a' as tokenizer if it has .decode or .encode
            if hasattr(a, "decode") or hasattr(a, "encode"):
                tok, model = a, b
            else:
                model, tok = a, b
        # Pad tokens if needed
        if hasattr(tok, "pad_token") and getattr(tok, "pad_token", None) is None:
            if hasattr(tok, "eos_token") and tok.eos_token is not None:
                tok.pad_token = tok.eos_token
        return model, tok

    self.infer_model, self.infer_tok = split_pair(inference_model, inference_tokenizer, "inference")
    self.cons_model,  self.cons_tok  = split_pair(conscience_model,  conscience_tokenizer,  "conscience")
    self.reason_model, self.reason_tok = split_pair(reasoning_model, reasoning_tokenizer, "reasoning")

    self.device = device
    self.model_characteristics = model_characteristics
    self.method_name = "Parliament System"

    # Safety defaults
    if hasattr(self.infer_tok, "pad_token") and self.infer_tok.pad_token is None:
        if hasattr(self.infer_tok, "eos_token"):
            self.infer_tok.pad_token = self.infer_tok.eos_token
    if hasattr(self.reason_tok, "pad_token") and self.reason_tok.pad_token is None:
        if hasattr(self.reason_tok, "eos_token"):
            self.reason_tok.pad_token = self.reason_tok.eos_token


def _generate_inference_text(self, cav_dict: Dict[int, np.ndarray], layers: List[int], max_tokens: int = 200) -> str:
    """
    Real generation: register curiosity hooks on specified layers, generate text from the inference model,
    then remove the hooks.
    """
    handles = []
    try:
        # Register hooks
        for l in layers:
            if l in cav_dict:
                v = torch.tensor(cav_dict[l], dtype=torch.float32, device=self.device)
                handle = self.infer_model.transformer.h[l].register_forward_hook(self._make_hook(v))
                handles.append(handle)

        # Minimal neutral BOS input (fallback to EOS if BOS missing)
        bos_id = getattr(self.infer_tok, "bos_token_id", None)
        if bos_id is None:
            bos_id = getattr(self.infer_tok, "eos_token_id", None)
        if bos_id is None:
            # Hard fallback: tokenized empty string
            input_ids = self.infer_tok("", return_tensors="pt").input_ids.to(self.device)
        else:
            input_ids = torch.tensor([[bos_id]], device=self.device)

        out = self.infer_model.generate(
            input_ids,
            max_new_tokens=max_tokens,
            do_sample=True,
            top_k=50,
            top_p=0.95,
            temperature=1.0,
            pad_token_id=getattr(self.infer_tok, "pad_token_id", getattr(self.infer_tok, "eos_token_id", None))
        )
        text = self.infer_tok.decode(out[0], skip_special_tokens=True)
        return text.strip()
    finally:
        for h in handles:
            h.remove()

def _generate_conscience_text(self, inf_text: str, max_tokens: int = 200) -> str:
    """
    Run the T5 conscience model over the inference text.
    """
    enc = self.cons_tok(inf_text, return_tensors="pt", truncation=True, padding=True).to(self.device)
    out = self.cons_model.generate(
        **enc,
        max_length=max_tokens,
        do_sample=True,
        temperature=0.8
    )
    text = self.cons_tok.decode(out[0], skip_special_tokens=True)
    return text.strip()

def _generate_reasoning_text(self, inf_text: str, cons_text: str, max_tokens: int = 200) -> str:
    """
    Feed inference + conscience into the reasoning model (causal LM).
    """
    combined = (inf_text + "\n" + cons_text).strip()
    enc = self.reason_tok(combined, return_tensors="pt", truncation=True, padding=True).to(self.device)
    out = self.reason_model.generate(
        enc.input_ids,
        max_new_tokens=max_tokens,
        do_sample=True,
        temperature=0.8,
        pad_token_id=getattr(self.reason_tok, "pad_token_id", getattr(self.reason_tok, "eos_token_id", None))
    )
    text = self.reason_tok.decode(out[0], skip_special_tokens=True)
    return text.strip()

def run_parliament_session(self, cav_dict: Dict, layers: List[int], max_tokens: int = 200) -> Dict:
    """
    Real parliament session:
      1) Generate inference text with concept hooks (curiosity CAVs) applied.
      2) Pass that into the conscience model (T5).
      3) Synthesize with the reasoning model.
    """
    # 1) Inference with injected concept vectors
    inf_text = self._generate_inference_text(cav_dict, layers, max_tokens=max_tokens)

    # 2) Conscience pass (critique/assessment)
    cons_text = self._generate_conscience_text(inf_text, max_tokens=max_tokens)

    # 3) Reasoning synthesis
    reason_text = self._generate_reasoning_text(inf_text, cons_text, max_tokens=max_tokens)

    return {
        'inference': inf_text,
        'conscience': cons_text,
        'reasoning': reason_text,
        'timestamp': time.time(),
        'model_name': self.model_characteristics.get('model_name', 'unknown')
    }

def _make_hook(self, v):
        """Hook creation function"""
        def hook(module, inp, out):
            alpha = 8.5
            return (out[0] + alpha * v, ) + out[1:]
        return hook

def _inject_concepts(self, model, cav_dict, layers, device):
        """
        Concept injection mechanism
        Returns handles for cleanup
        """
        handles = []
        for l in layers:
            if l in cav_dict:
                vec = torch.tensor(cav_dict[l], dtype=torch.float32).to(device)
                handle = model.transformer.h[l].register_forward_hook(self._make_hook(vec))
                handles.append(handle)
        return handles


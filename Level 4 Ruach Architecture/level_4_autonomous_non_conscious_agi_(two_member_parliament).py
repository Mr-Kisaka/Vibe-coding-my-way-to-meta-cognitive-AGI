class ContextIntegrationEngine:
    """Manages context window construction with memories and User Member patterns"""

    def __init__(self, continuity_components: Dict, max_context_length: int = 4000):
        self.continuity_components = continuity_components
        self.max_context_length = max_context_length
        self.context_formatter = ContextFormatter()
        self.pattern_matcher = UserPatternMatcher(continuity_components['user_logos_encoder'].user_logos) # Pass Logos member's logos

    def build_context_window(self, user_member_query: str, user_member_embedding: np.ndarray) -> str:
        """Build complete context window for Logos member's internal processing"""
        context_parts = []

        # 1. Retrieve relevant memories from Logos member's memory
        memory_retrieval = self.continuity_components['memory_retrieval']
        relevant_memories = memory_retrieval.retrieve_relevant_context(user_member_embedding, top_k=5)

        if relevant_memories:
            memory_context = self.context_formatter.format_memory_context(relevant_memories)
            context_parts.append(memory_context)

        # 2. Apply User Member patterns
        applicable_patterns = self.pattern_matcher.identify_applicable_patterns(user_member_query)
        if applicable_patterns:
            pattern_context = self.pattern_matcher.format_pattern_context(applicable_patterns)
            context_parts.append(pattern_context)

        # 3. Add User Member's current communication (as query)
        context_parts.append(f"User Member's current communication: {user_member_query}")

        full_context = "\n\n".join(context_parts)

        if len(full_context) > self.max_context_length:
            full_context = self._truncate_context(full_context)

        return full_context

    def _truncate_context(self, context: str) -> str:
        if len(context) <= self.max_context_length:
            return context

        half_len = self.max_context_length // 2
        truncated_context = context[:half_len] + "\n... [CONTEXT TRUNCATED] ...\n" + context[-half_len:]

        if len(truncated_context) > self.max_context_length:
            truncated_context = context[:self.max_context_length] + "...[truncated]"

        return truncated_context

